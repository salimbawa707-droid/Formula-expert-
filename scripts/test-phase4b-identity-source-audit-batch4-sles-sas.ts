assert.equal(rows[0][16], 'NOT_ESTABLISHED');
assert(rows[0][7].includes('echa.europa.eu'));
assert(rows[0][8].includes('kcia.or.kr'));
assert(rows[0][9].includes('precision.fda.gov'));
assert(rows[0][10].includes('industrialchemicals.gov.au'));
assert.equal(rows[1][1], '68585-34-2');
assert(rows[1][6].includes('68891-38-3'));
assert(rows[1][6].includes('9004-82-4'));
assert.equal(rows[1][14], 'GENERIC_CAS_ASSOCIATION_SUPPORTED_SCOPE_LIMITED');
assert.equal(rows[1][15], 'DO_NOT_PROMOTE_TO_SUPPLIER_GRADE_OR_LOT_IDENTITY');
