assert.equal(rows[0][1], '68037-49-0');
assert.equal(rows[0][6], '97489-15-1');
assert.equal(rows[0][14], 'CAS_INCI_ALTERNATE_IDENTIFIER_CONFLICT_REQUIRES_SOURCE_RESOLUTION');
