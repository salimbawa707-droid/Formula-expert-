/**
 * Protocol Hash Service
 * 
 * Provides deterministic cryptographic SHA-256 calculation for laboratory protocols,
 * exported scripts, and execution records.
 */

// Simple robust synchronous SHA-256 implementation in pure TypeScript
export function computeSha256(data: string): string {
  function rightRotate(value: number, amount: number): number {
    return (value >>> amount) | (value << (32 - amount));
  }

  const mathPow = Math.pow;
  const maxWord = mathPow(2, 32);
  let i = 0;
  let j = 0;

  const result: number[] = [];
  const words: number[] = [];
  const asciiBitLength = data.length * 8;

  const hash: number[] = [];
  const k: number[] = [];
  let primeCounter = 0;

  const isComposite: Record<number, boolean> = {};
  for (let candidate = 2; primeCounter < 64; candidate++) {
    if (!isComposite[candidate]) {
      for (i = 0; i < 300; i += candidate) {
        isComposite[i] = true;
      }
      hash[primeCounter] = (mathPow(candidate, 0.5) * maxWord) | 0;
      k[primeCounter++] = (mathPow(candidate, 1 / 3) * maxWord) | 0;
    }
  }

  let str = data;
  str += '\x80';
  while ((str.length % 64) - 56) str += '\x00';
  for (i = 0; i < str.length; i++) {
    j = str.charCodeAt(i);
    if (j >> 8) return '';
    words[i >> 2] |= j << (((3 - i) % 4) * 8);
  }
  words[words.length] = (asciiBitLength / maxWord) | 0;
  words[words.length] = asciiBitLength | 0;

  for (j = 0; j < words.length; ) {
    const w = words.slice(j, (j += 16));
    const oldHash = [...hash];

    for (i = 0; i < 64; i++) {
      const w15 = w[i - 15];
      const w2 = w[i - 2];

      const s0 = i < 16 ? w[i] : (
        (w[i] = (
          (w[i - 16] +
            (rightRotate(w15, 7) ^ rightRotate(w15, 18) ^ (w15 >>> 3)) +
            w[i - 7] +
            (rightRotate(w2, 17) ^ rightRotate(w2, 19) ^ (w2 >>> 10))) | 0
        ))
      );

      const s1 = rightRotate(hash[0], 2) ^ rightRotate(hash[0], 13) ^ rightRotate(hash[0], 22);
      const ch = (hash[0] & hash[1]) ^ (~hash[0] & hash[2]);
      const temp1 = (hash[7] + (rightRotate(hash[4], 6) ^ rightRotate(hash[4], 11) ^ rightRotate(hash[4], 25)) + ((hash[4] & hash[5]) ^ (~hash[4] & hash[6])) + k[i] + s0) | 0;
      const temp2 = (s1 + ch) | 0;

      hash[7] = hash[6];
      hash[6] = hash[5];
      hash[5] = hash[4];
      hash[4] = (hash[3] + temp1) | 0;
      hash[3] = hash[2];
      hash[2] = hash[1];
      hash[1] = hash[0];
      hash[0] = (temp1 + temp2) | 0;
    }

    for (i = 0; i < 8; i++) {
      hash[i] = (hash[i] + oldHash[i]) | 0;
    }
  }

  for (i = 0; i < 8; i++) {
    for (j = 3; j >= 0; j--) {
      const b = (hash[i] >> (j * 8)) & 255;
      result.push(b);
    }
  }

  return result.map(b => b.toString(16).padStart(2, '0')).join('');
}

/**
 * Computes canonical deterministic protocol hash from protocol parameters
 */
export function computeProtocolCanonicalHash(payload: {
  protocolId: string;
  protocolVersion: string;
  experimentId: string;
  formulaId?: string;
  robotPlatform: string;
  commands: unknown[];
  liquidTransfers: unknown[];
}): string {
  const canonicalString = JSON.stringify({
    protocolId: payload.protocolId,
    protocolVersion: payload.protocolVersion,
    experimentId: payload.experimentId,
    formulaId: payload.formulaId || '',
    robotPlatform: payload.robotPlatform,
    commands: payload.commands,
    liquidTransfers: payload.liquidTransfers,
  });

  return computeSha256(canonicalString);
}
