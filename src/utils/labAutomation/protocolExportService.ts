/**
 * Protocol Export Service
 * 
 * Generates verified export artifacts for external Opentrons robot execution:
 * 1. Opentrons Python Protocol (API v2.13 compatible script)
 * 2. Opentrons JSON Protocol (Schema v6 compatible specification)
 * 3. Standard Operating Procedure (SOP) Markdown
 * 4. Cryptographic Integrity Manifest
 * 
 * Never allows export of unvalidated or unapproved protocols.
 */

import { ProtocolDefinition, ProtocolExportBundle } from './types';
import { computeSha256 } from './protocolHashService';

/**
 * Generates Opentrons Python Protocol API v2.13 script
 */
export function generateOpentronsPythonScript(protocol: ProtocolDefinition): string {
  const lines: string[] = [];

  lines.push('# ==============================================================================');
  lines.push('# OPENTRONS PROTOCOL API v2.13 SCRIPT');
  lines.push(`# Protocol ID:      ${protocol.protocolId}`);
  lines.push(`# Protocol Version: ${protocol.protocolVersion}`);
  lines.push(`# Protocol Hash:    ${protocol.protocolHash}`);
  lines.push(`# Generated For:    ${protocol.protocolName}`);
  lines.push(`# Target Platform:  ${protocol.robotPlatform}`);
  lines.push('# ==============================================================================');
  lines.push('');
  lines.push('from opentrons import protocol_api');
  lines.push('');
  lines.push('metadata = {');
  lines.push(`    "protocolName": "${protocol.protocolName.replace(/"/g, '\\"')}",`);
  lines.push(`    "author": "${protocol.createdBy.replace(/"/g, '\\"')}",`);
  lines.push(`    "description": "Automated formulation screening protocol generated by Detergent Formula Expert",`);
  lines.push(`    "apiLevel": "${protocol.apiLevel}",`);
  lines.push('}');
  lines.push('');
  lines.push('def run(protocol: protocol_api.ProtocolContext):');
  lines.push('    # 1. Deck & Labware Setup');

  // Load Labware
  for (const [slot, item] of Object.entries(protocol.deckLayout)) {
    if (item.labwareDef.category === 'trash') continue;
    const varName = `labware_slot_${slot}`;
    lines.push(`    ${varName} = protocol.load_labware("${item.labwareDef.loadName}", "${slot}", "${item.nickname.replace(/"/g, '\\"')}")`);
  }

  lines.push('');
  lines.push('    # 2. Pipette Setup');
  if (protocol.pipettes.left) {
    const tipRackVar = 'labware_slot_1'; // Standard slot 1 tiprack
    lines.push(`    pipette_left = protocol.load_instrument(`);
    lines.push(`        "${protocol.pipettes.left.pipetteDef.model}",`);
    lines.push(`        "left",`);
    lines.push(`        tip_racks=[${tipRackVar}] if "${tipRackVar}" in locals() else []`);
    lines.push(`    )`);
  }

  if (protocol.pipettes.right) {
    const tipRackVar = 'labware_slot_1';
    lines.push(`    pipette_right = protocol.load_instrument(`);
    lines.push(`        "${protocol.pipettes.right.pipetteDef.model}",`);
    lines.push(`        "right",`);
    lines.push(`        tip_racks=[${tipRackVar}] if "${tipRackVar}" in locals() else []`);
    lines.push(`    )`);
  }

  lines.push('');
  lines.push('    # 3. Protocol Commands Execution');

  let activeTipPipette: string | null = null;

  for (const cmd of protocol.commands) {
    switch (cmd.type) {
      case 'PICK_UP_TIP': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        lines.push(`    ${pipVar}.pick_up_tip()`);
        activeTipPipette = pipVar;
        break;
      }
      case 'ASPIRATE': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        const labVar = `labware_slot_${cmd.labwareSlot}`;
        lines.push(`    ${pipVar}.aspirate(${cmd.volumeUl}, ${labVar}["${cmd.well}"])`);
        break;
      }
      case 'DISPENSE': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        const labVar = `labware_slot_${cmd.labwareSlot}`;
        lines.push(`    ${pipVar}.dispense(${cmd.volumeUl}, ${labVar}["${cmd.well}"])`);
        break;
      }
      case 'TOUCH_TIP': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        lines.push(`    ${pipVar}.touch_tip()`);
        break;
      }
      case 'MIX': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        const labVar = `labware_slot_${cmd.labwareSlot}`;
        lines.push(`    ${pipVar}.mix(${cmd.cycles || 5}, ${cmd.volumeUl}, ${labVar}["${cmd.well}"])`);
        break;
      }
      case 'DROP_TIP': {
        const pipVar = cmd.pipetteMount === 'left' ? 'pipette_left' : 'pipette_right';
        lines.push(`    ${pipVar}.drop_tip()`);
        activeTipPipette = null;
        break;
      }
      case 'PAUSE': {
        lines.push(`    protocol.pause("${(cmd.pauseMessage || 'Operator confirmation required').replace(/"/g, '\\"')}")`);
        break;
      }
      default:
        break;
    }
  }

  if (activeTipPipette) {
    lines.push(`    ${activeTipPipette}.drop_tip()`);
  }

  lines.push('');
  lines.push('    protocol.comment("Protocol run completed successfully.")');
  return lines.join('\n');
}

/**
 * Generates JSON Protocol specification
 */
export function generateJsonProtocolSpec(protocol: ProtocolDefinition): string {
  return JSON.stringify(
    {
      $schema: 'https://schema.opentrons.com/protocol/v6.json',
      schemaVersion: 6,
      metadata: {
        protocolName: protocol.protocolName,
        author: protocol.createdBy,
        description: 'Automated formulation protocol export',
        created: protocol.createdAt,
        protocolId: protocol.protocolId,
        protocolVersion: protocol.protocolVersion,
        protocolHash: protocol.protocolHash,
      },
      robot: {
        model: protocol.robotPlatform === 'OT-2' ? 'OT-2 Standard' : 'Opentrons Flex',
      },
      pipettes: protocol.pipettes,
      labware: protocol.deckLayout,
      commands: protocol.commands,
      liquidTransfers: protocol.liquidTransfers,
      mixOperations: protocol.mixOperations,
      validation: {
        isValid: protocol.validationResult.isValid,
        status: protocol.validationResult.status,
        hash: protocol.protocolHash,
      },
    },
    null,
    2
  );
}

/**
 * Generates SOP Markdown documentation
 */
export function generateSopMarkdown(protocol: ProtocolDefinition): string {
  const lines: string[] = [];

  lines.push(`# Standard Operating Procedure (SOP)`);
  lines.push(`## ${protocol.protocolName}`);
  lines.push(`- **Protocol ID**: \`${protocol.protocolId}\``);
  lines.push(`- **Version**: \`${protocol.protocolVersion}\``);
  lines.push(`- **Platform**: ${protocol.robotPlatform}`);
  lines.push(`- **SHA-256 Hash**: \`${protocol.protocolHash}\``);
  lines.push(`- **Created**: ${protocol.createdAt}`);
  lines.push(`- **Created By**: ${protocol.createdBy}`);
  lines.push('');
  lines.push(`### 1. Deck Layout Requirements`);
  lines.push(`| Slot | Labware | Nickname | Purpose |`);
  lines.push(`| :--- | :--- | :--- | :--- |`);

  for (const [slot, item] of Object.entries(protocol.deckLayout)) {
    lines.push(`| ${slot} | ${item.labwareDef.displayName} | ${item.nickname} | ${item.purpose} |`);
  }

  lines.push('');
  lines.push(`### 2. Pipette Hardware Configuration`);
  if (protocol.pipettes.left) {
    lines.push(`- **Left Mount**: ${protocol.pipettes.left.pipetteDef.displayName}`);
  }
  if (protocol.pipettes.right) {
    lines.push(`- **Right Mount**: ${protocol.pipettes.right.pipetteDef.displayName}`);
  }

  lines.push('');
  lines.push(`### 3. Reagents & Initial Stock Preparation`);
  for (const [slot, item] of Object.entries(protocol.deckLayout)) {
    if (item.initialContents && Object.keys(item.initialContents).length > 0) {
      lines.push(`#### Slot ${slot} (${item.nickname})`);
      for (const [well, content] of Object.entries(item.initialContents)) {
        lines.push(`- **Well ${well}**: ${content.ingredientName || 'Reagent'} (Stock: ${content.concentrationPercent ?? 'N/A'}%, Initial Vol: ${content.initialVolumeUl} µL)`);
      }
    }
  }

  lines.push('');
  lines.push(`### 4. Summary of Protocol Operations`);
  lines.push(`- **Total Commands**: ${protocol.commands.length}`);
  lines.push(`- **Total Liquid Transfers**: ${protocol.liquidTransfers.length}`);
  lines.push(`- **Total Tips Required**: ${protocol.totalTipsRequired}`);
  lines.push(`- **Estimated Duration**: ~${protocol.estimatedDurationMinutes} minutes`);
  lines.push('');
  lines.push(`### 5. Operator Safety & Environmental Notes`);
  lines.push(`- Confirm all labware are seated flat in deck slots.`);
  lines.push(`- Ensure tip box lids are removed before starting run.`);
  lines.push(`- Wear appropriate PPE for handling surfactant concentrates and builders.`);
  lines.push(`- Verify room temperature is within 20-25°C.`);

  return lines.join('\n');
}

/**
 * Creates a complete Protocol Export Bundle
 */
export function exportProtocolBundle(
  protocol: ProtocolDefinition,
  exportedBy: string
): ProtocolExportBundle {
  if (!protocol.approvedForExport) {
    throw new Error(`Protocol '${protocol.protocolId}' has not been approved for export through the Human Review Gate.`);
  }

  const pythonScript = generateOpentronsPythonScript(protocol);
  const jsonSpec = generateJsonProtocolSpec(protocol);
  const sopMarkdown = generateSopMarkdown(protocol);

  const manifest = JSON.stringify(
    {
      protocolId: protocol.protocolId,
      protocolVersion: protocol.protocolVersion,
      protocolHash: protocol.protocolHash,
      robotPlatform: protocol.robotPlatform,
      scriptHash: computeSha256(pythonScript),
      jsonSpecHash: computeSha256(jsonSpec),
      sopHash: computeSha256(sopMarkdown),
      exportedAt: new Date().toISOString(),
      exportedBy,
    },
    null,
    2
  );

  return {
    protocolId: protocol.protocolId,
    protocolVersion: protocol.protocolVersion,
    protocolHash: protocol.protocolHash,
    robotPlatform: protocol.robotPlatform,
    apiLevel: protocol.apiLevel,
    pythonProtocolScript: pythonScript,
    jsonProtocolSpec: jsonSpec,
    sopMarkdown,
    manifestJson: manifest,
    exportedAt: new Date().toISOString(),
    exportedBy,
  };
}
